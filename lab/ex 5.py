
# List Operations

L1 = [10, 20, 30, 40]
L2 = [50, 60]

# Nested List
L3 = [L1, L2]
print("Nested List:", L3)

# Length
print("Length:", len(L1))

# Concatenation
print("Concatenation:", L1 + L2)

# Membership
print("Membership:", 20 in L1)

# Iteration
print("Iteration:")
for i in L1:
    print(i)

# Indexing
print("Indexing:", L1[2])

# Slicing
print("Slicing:", L1[1:3])

